    function addToCartFromModal(id) {
      const product = products.find(p => p.id === id);
      const item = cart.find(i => i.id === id && i.variant === selectedVariant);
      if(item) {
        item.qty++;
      } else {
        cart.push({ ...product, variant: selectedVariant || 'Standar', qty: 1 });
      }
      updateCartUI();
      closeProductModal();
      toggleCartModal();
    }

    function updateCartUI() {
      const count = cart.reduce((acc, i) => acc + i.qty, 0);
      const cartCountEl = document.getElementById('cartCount');
      if (count > 0) {
        cartCountEl.textContent = count;
        cartCountEl.classList.remove('hidden');
      } else {
        cartCountEl.classList.add('hidden');
      }

      const cartItemsEl = document.getElementById('cartItems');

      if (cart.length === 0) {
        cartItemsEl.innerHTML = `<div class="text-center text-gray-400 py-8 text-sm">Keranjang Anda masih kosong.</div>`;
      } else {
        cartItemsEl.innerHTML = cart.map((item, index) => `
          <div class="flex items-center justify-between gap-3 border-b border-gray-800 pb-3">
            <img src="${item.img}" class="w-12 h-12 rounded-lg object-cover bg-gray-800">
            <div class="flex-1">
              <h4 class="text-xs font-semibold text-white line-clamp-1">${item.name}</h4>
              <p class="text-[10px] text-gray-400">Varian: ${item.variant}</p>
              <p class="text-xs font-bold text-white">${formatRupiah(item.price)}</p>
            </div>
            <div class="flex items-center gap-2">
              <button onclick="changeCartQty(${index}, -1)" class="w-6 h-6 bg-gray-800 rounded-md text-xs font-bold text-white">-</button>
              <span class="text-xs font-semibold text-white">${item.qty}</span>
              <button onclick="changeCartQty(${index}, 1)" class="w-6 h-6 bg-gray-800 rounded-md text-xs font-bold text-white">+</button>
            </div>
          </div>
        `).join('');
      }

      const total = cart.reduce((acc, i) => acc + (i.price * i.qty), 0);
      document.getElementById('cartTotal').textContent = formatRupiah(total);
    }

    function changeCartQty(index, delta) {
      cart[index].qty += delta;
      if(cart[index].qty <= 0) cart.splice(index, 1);
      updateCartUI();
    }

