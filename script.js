    function processUserLogin() {
      const userVal = document.getElementById('loginUsernameInput').value.trim().toLowerCase();
      const passVal = document.getElementById('loginPasswordInput').value.trim();

      if (!userVal || !passVal) return triggerCustomAlert("Login Gagal", "Mohon isi username/email dan password!");

      const found = registeredUsers.find(u => 
        (u.username.toLowerCase() === userVal || (u.email && u.email.toLowerCase() === userVal) || u.name.toLowerCase() === userVal) && u.password === passVal
      );

      if (found) {
        currentUser = found;
        saveData();
        renderUserAuthStatusUI();
        closeUserAuthModal();
        triggerCustomAlert("Selamat Datang!", `Login berhasil. Selamat datang kembali, ${found.name}!`);
      } else {
        triggerCustomAlert("Login Gagal", "Username atau Password yang Anda masukkan tidak terdaftar!");
      }
    }


    function processUserRegister() {
      const name = document.getElementById('regNameInput').value.trim();
      const email = document.getElementById('regEmailInput').value.trim().toLowerCase();
      const username = document.getElementById('regUsernameInput').value.trim().toLowerCase();
      const phone = document.getElementById('regWaInput').value.trim();
      const pass = document.getElementById('regPasswordInput').value.trim();

      if (!name || !email || !username || !phone || !pass) return triggerCustomAlert("Pendaftaran Gagal", "Mohon lengkapi seluruh formulir pendaftaran!");
      if (!email.endsWith('@gmail.com')) return triggerCustomAlert("Pendaftaran Gagal", "Email wajib menggunakan format @gmail.com (Contoh: nama@gmail.com)!");

      const existUser = registeredUsers.find(u => u.username.toLowerCase() === username || (u.email && u.email.toLowerCase() === email));
      if (existUser) return triggerCustomAlert("Pendaftaran Gagal", "Username atau Email ini sudah dipakai oleh pengguna lain!");

      const nowStr = new Date().toISOString().slice(0, 16).replace('T', ' ');
      const newUser = {
        id: Date.now(),
        name,
        username,
        email,
        phone,
        password: pass,
        regDate: nowStr
      };

      registeredUsers.push(newUser);
      currentUser = newUser;
      saveData();

      renderUserAuthStatusUI();
      renderAdminUsers();
      clearUserAuthInputs();
      closeUserAuthModal();
      triggerCustomAlert("Pendaftaran Berhasil", `Akun berhasil dibuat! Anda sekarang masuk sebagai ${name}.`);
    }


