    function renderAnalytics() {
      const totalRev = orders.reduce((acc, o) => acc + (o.status === 'Sukses' || o.status === 'Selesai' ? o.paidAmount : 0), 0);
      const totalSuccOrders = orders.filter(o => o.status === 'Sukses' || o.status === 'Selesai').length;
      document.getElementById('statTotalRevenue').textContent = formatRupiah(totalRev);
      document.getElementById('statTotalOrders').textContent = totalSuccOrders;
      document.getElementById('statTotalUsersCount').textContent = registeredUsers.length;

      // Best sellers
      const counts = {};
      orders.forEach(o => {
        if (o.status === 'Sukses' || o.status === 'Selesai' || o.status === 'Dikirim' || o.status === 'Diproses') {
          counts[o.productName] = (counts[o.productName] || 0) + o.qty;
        }
      });

      const bestList = document.getElementById('adminBestSellersList');
      const sorted = Object.entries(counts).sort((a,b) => b[1] - a[1]);
      if (sorted.length === 0) {
        bestList.innerHTML = `<p class="text-xs text-gray-400">Belum ada data penjualan produk.</p>`;
      } else {
        bestList.innerHTML = sorted.map(([name, qty]) => `
          <div class="flex justify-between items-center p-3 bg-gray-800/50 rounded-xl border border-gray-700 text-xs">
            <span class="font-bold text-white">${name}</span>
            <span class="bg-indigo-600 text-white px-2.5 py-1 rounded-full font-bold">Terjual: ${qty} pcs</span>
          </div>
        `).join('');
      }
    }

