    function saveProductData() {
      const id = document.getElementById('editProductId').value;
      const name = document.getElementById('prodNameInput').value.trim();
      const price = parseInt(document.getElementById('prodPriceInput').value) || 0;
      const category = document.getElementById('prodCategoryInput').value;
      const stock = parseInt(document.getElementById('prodStockInput').value) || 0;
      const variants = document.getElementById('prodVariantsInput').value.split(',').map(v => v.trim()).filter(v => v);
      const dpType = document.getElementById('prodDpTypeInput').value;
      const dpValue = parseFloat(document.getElementById('prodDpValueInput').value) || 0;
      
      const urlImg = document.getElementById('prodImgInput').value.trim();
      const defaultImg = "https://images.unsplash.com/photo-1521572267360-ee0c2909d518?w=500&auto=format&fit=crop";
      const finalImg = tempProductImageBase64 || urlImg || defaultImg;
      const desc = document.getElementById('prodDescInput').value.trim() || name;

      if(!name || !price) {
        return triggerCustomAlert("Peringatan", "Mohon isi Nama Produk dan Harga Total!");
      }

      const isTimeLimited = document.getElementById('prodIsTimeLimited').checked;
      const isUnlimited = document.getElementById('prodIsUnlimited').checked;
      const finalStock = isUnlimited ? 99999 : stock;
      const customBadgeText = document.getElementById('prodCustomBadgeText').value.trim();
      const startDate = document.getElementById('prodStartDate').value;
      const endDate = document.getElementById('prodEndDate').value;

      if(id) {
        const p = products.find(prod => prod.id == id);
        p.name = name; p.price = price; p.category = category; p.stock = finalStock; p.isUnlimited = isUnlimited;
        p.variants = variants; p.dpType = dpType; p.dpValue = dpValue; p.img = finalImg; p.desc = desc;
        p.isTimeLimited = isTimeLimited; p.customBadgeText = customBadgeText; p.startDate = startDate; p.endDate = endDate;
      } else {
        products.push({ id: Date.now(), name, category, price, stock: finalStock, isUnlimited, variants, dpType, dpValue, img: finalImg, desc, isTimeLimited, customBadgeText, startDate, endDate });
      }

      saveData();
      closeProductAdminModal();
      renderAdminProducts();
      renderAnalytics();
      
      selectedCategory = category;
      renderCategories();
      renderProducts();

      triggerCustomAlert("Sukses", "Data produk berhasil disimpan!");
    }

